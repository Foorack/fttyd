#!/usr/bin/env bash
# Rejects commits that attribute authorship to an AI model.
#
#   scripts/check-authors.sh                 # every commit reachable from any ref
#   scripts/check-authors.sh main..HEAD      # a revision range
#   scripts/check-authors.sh --message-file .git/COMMIT_EDITMSG   # a single message
#
# What counts as attribution:
#   * an identity (author or committer, name or email) that names a model,
#   * an attribution trailer (Co-authored-by, Assisted-by, Generated-by, ...) whose
#     value names a model,
#   * a "generated with <model>" style line.
#
# Mentioning a model in prose is *not* an offence: commit messages about removing such
# attribution are legitimate.
set -uo pipefail

# Model and vendor tokens, matched case-insensitively.
readonly AI_TOKENS='copilot|claude|chatgpt|openai|anthropic|gpt-?[0-9]|gpt4|gemini|bard|codeium|windsurf|tabnine|amazon-q|amazon q|devin|aider|continue\.dev|mistral|llama[0-9]|meta-llama|codex|deepseek|grok|perplexity|replit|sourcegraph|cody|qwen|kimi|gemma|phi-[0-9]|huggingface|cursor-agent|cursor agent|github-copilot|code-llama|starcoder|vicuna|alpaca'

# Trailer keys that claim authorship.
readonly ATTRIBUTION_KEYS='co-authored-by|co-authored|co-developed-by|assisted-by|generated-by|authored-by|contributed-by|written-by|created-by|signed-off-by-ai|ai-assistant'

# Domains that only ever belong to a model vendor.
readonly AI_DOMAINS='anthropic\.com|openai\.com|copilot\.com|copilot\.microsoft\.com|deepmind\.com|huggingface\.co|cursor\.(sh|com)'

failures=0

report() {
  # report <sha> <what> <detail>
  printf '\n\033[1mcommit %s\033[0m\n  %s: %s\n' "$1" "$2" "$3" >&2
  failures=$((failures + 1))
}

# check_text <sha> <full message>
check_message() {
  local sha="$1" message="$2" line lower

  while IFS= read -r line; do
    lower="${line,,}"

    # Attribution trailer naming a model.
    if [[ "$lower" =~ ^[[:space:]]*($ATTRIBUTION_KEYS)[[:space:]]*: ]]; then
      if [[ "$lower" =~ $AI_TOKENS ]]; then
        report "$sha" "AI attribution trailer" "$line"
        continue
      fi
    fi

    # "Generated with Claude Code", "🤖 Generated by Copilot", ...
    if [[ "$lower" =~ (generated|created|written|authored|produced|assisted|made)[[:space:]]+(with|by|using) ]] \
      && [[ "$lower" =~ $AI_TOKENS ]]; then
      report "$sha" "AI-generated notice" "$line"
      continue
    fi
  done <<< "$message"
}

# check_identity <sha> "name <email>"
check_identity() {
  local sha="$1" identity="$2" lower="${2,,}"
  if [[ "$lower" =~ $AI_TOKENS ]] || [[ "$lower" =~ $AI_DOMAINS ]]; then
    report "$sha" "AI identity" "$identity"
  fi
}

check_commit() {
  local sha="$1"
  check_message "$sha" "$(git log -1 --format='%B' "$sha")"
  check_identity "$sha" "$(git log -1 --format='%an <%ae>' "$sha")"
  check_identity "$sha" "$(git log -1 --format='%cn <%ce>' "$sha")"
}

check_message_file() {
  local file="$1"
  [[ -f "$file" ]] || { echo "error: no such message file: $file" >&2; exit 2; }
  # Comment lines are stripped from commit messages, so ignore them here too.
  check_message "(message)" "$(grep -v '^#' "$file")"
}

usage() {
  sed -n '2,12p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
  exit 2
}

main() {
  case "${1:-}" in
    -h|--help) usage ;;
    --message-file)
      [[ $# -eq 2 ]] || usage
      check_message_file "$2"
      ;;
    "")
      while IFS= read -r sha; do check_commit "$sha"; done < <(git rev-list --all)
      ;;
    *)
      local range="$1"
      local commits
      commits="$(git rev-list "$range" 2>/dev/null)"
      if [[ -z "$commits" ]]; then
        echo "error: '$range' matches no commits" >&2
        exit 2
      fi
      while IFS= read -r sha; do check_commit "$sha"; done <<< "$commits"
      ;;
  esac

  if [[ "$failures" -gt 0 ]]; then
    cat >&2 <<'EOF'

────────────────────────────────────────────────────────────────────────
AI models must not be credited as authors in this repository.

Fix the offending commits, for example:
  git commit --amend                      # the newest commit
  git rebase -i <base>                    # older ones, then 'reword'
  git rebase --exec 'git commit --amend --no-edit -m "$(git log -1 --format=%B | grep -vi "co-authored-by")"' <base>

The forbidden identity is any author/committer or attribution trailer that names an
AI model or its vendor (Copilot, Claude, ChatGPT, Gemini, Cursor, Codex, and so on).
EOF
    printf '%s offending commit(s).\n' "$failures" >&2
    exit 1
  fi

  echo "no AI attribution found."
}

main "$@"
