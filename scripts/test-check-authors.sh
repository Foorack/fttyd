#!/usr/bin/env bash
# Exercises scripts/check-authors.sh against real commits, because a check that never
# fires is worse than no check at all.
set -uo pipefail

script="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/check-authors.sh"
failures=0

new_repo() {
  local dir
  dir="$(mktemp -d)"
  git -C "$dir" init -q
  git -C "$dir" config user.name "Foorack"
  git -C "$dir" config user.email "max@foorack.com"
  echo "$dir"
}

commit() { # commit <dir> <message> [name] [email]
  local dir="$1" message="$2" name="${3:-Foorack}" email="${4:-max@foorack.com}"
  echo "$RANDOM" >> "$dir/file"
  git -C "$dir" add file
  git -C "$dir" -c user.name="$name" -c user.email="$email" commit -q -m "$message"
}

expect() { # expect <pass|fail> <description> <dir>
  local want="$1" description="$2" dir="$3" got
  if (cd "$dir" && "$script" >/dev/null 2>&1); then got=pass; else got=fail; fi
  if [[ "$got" == "$want" ]]; then
    echo "ok: $description"
  else
    echo "FAIL: $description (expected $want, got $got)"
    failures=$((failures + 1))
  fi
  rm -rf "$dir"
}

# A plain, honest commit passes.
dir="$(new_repo)"; commit "$dir" "Add the sidebar"; expect pass "clean commit" "$dir"

# Attribution trailers naming a model are rejected.
dir="$(new_repo)"
commit "$dir" "$(printf 'Add the sidebar\n\nCo-authored-by: Copilot <223556219+Copilot@users.noreply.github.com>')"
expect fail "copilot co-author trailer" "$dir"

dir="$(new_repo)"
commit "$dir" "$(printf 'Add the sidebar\n\nCo-authored-by: Claude <noreply@anthropic.com>')"
expect fail "claude co-author trailer" "$dir"

dir="$(new_repo)"
commit "$dir" "$(printf 'Add the sidebar\n\nAssisted-by: ChatGPT <noreply@openai.com>')"
expect fail "assisted-by trailer" "$dir"

# "Generated with" notices are rejected even without a trailer.
dir="$(new_repo)"
commit "$dir" "$(printf 'Add the sidebar\n\n\360\237\244\226 Generated with [Claude Code](https://claude.com/claude-code)')"
expect fail "generated-with notice" "$dir"

dir="$(new_repo)"
commit "$dir" "$(printf 'Add the sidebar\n\nGenerated by Copilot')"
expect fail "generated-by notice" "$dir"

# Model identities are rejected wherever they appear in the identity.
dir="$(new_repo)"; commit "$dir" "Add the sidebar" "ChatGPT" "bot@example.com"
expect fail "AI author name" "$dir"

dir="$(new_repo)"; commit "$dir" "Add the sidebar" "Foorack" "copilot@example.com"
expect fail "AI author email" "$dir"

# Legitimate humans and non-AI trailers still pass.
dir="$(new_repo)"
commit "$dir" "$(printf 'Add the sidebar\n\nCo-authored-by: Jane Doe <jane@example.com>')"
expect pass "human co-author" "$dir"

dir="$(new_repo)"
commit "$dir" "$(printf 'Add the sidebar\n\nSigned-off-by: Foorack <max@foorack.com>')"
expect pass "signed-off-by" "$dir"

# Talking about the ban is not the same as doing it.
dir="$(new_repo)"
commit "$dir" "Strip the Copilot co-author trailer from history"
expect pass "prose mentioning a model" "$dir"

# --message-file, used by the commit-msg hook.
dir="$(new_repo)"
message_file="$dir/msg"
printf 'Add the sidebar\n\nCo-authored-by: Copilot <223556219+Copilot@users.noreply.github.com>\n' > "$message_file"
if (cd "$dir" && "$script" --message-file "$message_file" >/dev/null 2>&1); then
  echo "FAIL: message-file with trailer should fail"
  failures=$((failures + 1))
else
  echo "ok: message-file with trailer rejected"
fi
printf 'Add the sidebar\n\n# a comment mentioning Copilot\n' > "$message_file"
if (cd "$dir" && "$script" --message-file "$message_file" >/dev/null 2>&1); then
  echo "ok: message-file ignores comments"
else
  echo "FAIL: message-file with only a comment should pass"
  failures=$((failures + 1))
fi
rm -rf "$dir"

# A revision range only looks at the range.
dir="$(new_repo)"
commit "$dir" "$(printf 'Add the sidebar\n\nCo-authored-by: Copilot <223556219+Copilot@users.noreply.github.com>')"
first="$(git -C "$dir" rev-parse HEAD)"
commit "$dir" "Add the sidebar part two"
if (cd "$dir" && "$script" "$first..HEAD" >/dev/null 2>&1); then
  echo "ok: range ignores commits outside it"
else
  echo "FAIL: range should only inspect its commits"
  failures=$((failures + 1))
fi
if (cd "$dir" && "$script" >/dev/null 2>&1); then
  echo "FAIL: full history should catch the bad commit"
  failures=$((failures + 1))
else
  echo "ok: full history catches the bad commit"
fi
rm -rf "$dir"

echo
if [[ "$failures" -ne 0 ]]; then
  echo "$failures check(s) failed"
  exit 1
fi
echo "author check behaves as intended"
